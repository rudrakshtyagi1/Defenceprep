export const getPaperById = (id: string): Paper | undefined =>
  PAPERS.find((p) => p.id === id);

export const getPapersByExam = (examCode: string): Paper[] =>
  PAPERS.filter((p) => p.examCode === examCode);

export const getUniqueYears = (): number[] =>
  [...new Set(PAPERS.map((p) => p.year))].sort((a, b) => b - a);

export const getUniqueSubjects = (): string[] =>
  [...new Set(PAPERS.map((p) => p.subject))].sort();
